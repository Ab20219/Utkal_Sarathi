/**
 * Finds the nearest Odisha district from any WGS84 GPS coordinate using great-circle Haversine distance.
 */
export function findNearestDistrictByGps(
  latitude: number,
  longitude: number
): { point: DistrictGeoPoint; distanceKm: number } {
  const toRad = (deg: number) => (deg * Math.PI) / 180;
  const R = 6371;
  const entries = Object.values(DISTRICT_MAP_POINTS);
  let bestPoint = entries[0];
  let bestDistance = Number.POSITIVE_INFINITY;

  for (const pt of entries) {
    const dLat = toRad(pt.lat - latitude);
    const dLon = toRad(pt.lng - longitude);
    const a =
      Math.sin(dLat / 2) * Math.sin(dLat / 2) +
      Math.cos(toRad(latitude)) *
        Math.cos(toRad(pt.lat)) *
        Math.sin(dLon / 2) *
        Math.sin(dLon / 2);
    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
    const dist = R * c;
    if (dist < bestDistance) {
      bestDistance = dist;
      bestPoint = pt;
    }
  }

  return {
    point: bestPoint,
    distanceKm: Math.round(bestDistance * 10) / 10,
  };
}
